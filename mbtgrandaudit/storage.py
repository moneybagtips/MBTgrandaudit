"""Prediction log: predictions, per-model matrices, odds snapshots and results.

Two backends share one schema and one set of queries:
* Postgres (e.g. Supabase) when DATABASE_URL is set in the environment or in .env.
  Tables live in their own schema (default ``mbtgrandaudit``), so Supabase's
  auto-generated REST API does not expose them.
* SQLite (data/predictions.db) otherwise, for local use and tests.

Score matrices are stored as zlib-compressed float32 blobs, so any market
(including ones added later) can be recomputed exactly from the log.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sqlite3
import zlib
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from .config import ROOT

DB_FILE = ROOT / "data" / "predictions.db"
ENV_FILE = ROOT / ".env"

# {ID} {BLOB} {FLOAT} {BIGINT} are filled in per backend
SCHEMA = """
CREATE TABLE IF NOT EXISTS predictions (
    id            {ID},
    event_id      TEXT NOT NULL,
    league        TEXT NOT NULL,
    home          TEXT NOT NULL,          -- display names (ESPN)
    away          TEXT NOT NULL,
    model_home    TEXT,                   -- football-data names used by the models
    model_away    TEXT,
    kickoff       TEXT NOT NULL,          -- ISO 8601 UTC, fixed format (sorts chronologically)
    predicted_at  TEXT NOT NULL,
    model_version TEXT NOT NULL,
    source        TEXT NOT NULL,          -- 'live' or 'backtest'
    matrix        {BLOB} NOT NULL,        -- ensemble scoreline probabilities
    markets       TEXT NOT NULL,          -- JSON
    weights       TEXT NOT NULL,          -- JSON
    features      TEXT NOT NULL,          -- JSON
    UNIQUE (event_id, predicted_at, model_version, source)
);
CREATE INDEX IF NOT EXISTS ix_pred_event ON predictions(event_id);
CREATE INDEX IF NOT EXISTS ix_pred_kickoff ON predictions(kickoff);
CREATE TABLE IF NOT EXISTS model_outputs (
    prediction_id {BIGINT} NOT NULL REFERENCES predictions(id) ON DELETE CASCADE,
    model         TEXT NOT NULL,
    weight        {FLOAT} NOT NULL,
    matrix        {BLOB} NOT NULL,
    PRIMARY KEY (prediction_id, model)
);
CREATE TABLE IF NOT EXISTS odds (
    event_id     TEXT NOT NULL,
    captured_at  TEXT NOT NULL,
    kind         TEXT NOT NULL,           -- 'prediction' or 'closing'
    source       TEXT,
    home {FLOAT}, draw {FLOAT}, away {FLOAT},
    line {FLOAT}, over_odds {FLOAT}, under_odds {FLOAT},
    PRIMARY KEY (event_id, captured_at, kind)
);
CREATE TABLE IF NOT EXISTS market_odds (   -- any market, e.g. odds you enter by hand
    event_id     TEXT NOT NULL,
    market       TEXT NOT NULL,           -- markets() key: gg2_yes, btts_no, over_3.5, home ...
    captured_at  TEXT NOT NULL,
    kind         TEXT NOT NULL,           -- 'manual', 'prediction', 'closing'
    bookmaker    TEXT NOT NULL DEFAULT '',
    odds         {FLOAT} NOT NULL,
    PRIMARY KEY (event_id, market, captured_at, kind, bookmaker)
);
CREATE TABLE IF NOT EXISTS results (
    event_id   TEXT PRIMARY KEY,
    league     TEXT,
    home_goals INTEGER NOT NULL,
    away_goals INTEGER NOT NULL,
    settled_at TEXT NOT NULL,
    source     TEXT
)
"""
TYPES = {
    "sqlite": {"ID": "INTEGER PRIMARY KEY", "BLOB": "BLOB", "FLOAT": "REAL", "BIGINT": "INTEGER"},
    "postgres": {"ID": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "BLOB": "BYTEA",
                 "FLOAT": "DOUBLE PRECISION", "BIGINT": "BIGINT"},
}
PRED_COLS = ["event_id", "league", "home", "away", "model_home", "model_away", "kickoff", "predicted_at",
             "model_version", "source", "matrix", "markets", "weights", "features"]
ODDS_COLS = ["event_id", "captured_at", "kind", "source", "home", "draw", "away", "line",
             "over_odds", "under_odds"]
RESULT_COLS = ["event_id", "league", "home_goals", "away_goals", "settled_at", "source"]
MARKET_ODDS_COLS = ["event_id", "market", "captured_at", "kind", "bookmaker", "odds"]


def _upsert(table: str, cols: list[str], key: list[str], returning: str | None = None) -> str:
    upd = ", ".join(f"{c} = excluded.{c}" for c in cols if c not in key)
    sql = (f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})"
           f" ON CONFLICT ({', '.join(key)}) DO UPDATE SET {upd}")
    return sql + (f" RETURNING {returning}" if returning else "")


# ------------------------------------------------------------------- helpers
def pack(m: np.ndarray) -> bytes:
    m = np.asarray(m, dtype=np.float32)
    return zlib.compress(np.array(m.shape, dtype=np.int16).tobytes() + m.tobytes())


def unpack(b: bytes) -> np.ndarray:
    raw = zlib.decompress(bytes(b))
    shape = tuple(np.frombuffer(raw[:4], dtype=np.int16))
    m = np.frombuffer(raw[4:], dtype=np.float32).reshape(shape).astype(float)
    return m / m.sum()


NON_MODEL_SETTINGS = {"min_edge", "max_disagreement"}   # settings that don't change predictions


def model_version(settings) -> str:
    """Hash of model code + settings: predictions from different versions stay distinguishable."""
    pkg = Path(__file__).resolve().parent
    cfg = {k: v for k, v in asdict(settings).items() if k not in NON_MODEL_SETTINGS}
    h = hashlib.sha1(repr(cfg).encode())
    files = sorted((pkg / "models").glob("*.py")) + [pkg / "markets.py", pkg / "implied.py"]
    for f in files + [ROOT / "ensemble_weights.json"]:
        if f.exists():
            h.update(f.read_bytes().replace(b"\r\n", b"\n"))   # same hash on Windows and Linux
    return h.hexdigest()[:10]


def _iso(dt) -> str:
    ts = pd.Timestamp(dt)
    ts = ts.tz_localize("UTC") if ts.tzinfo is None else ts.tz_convert("UTC")
    return ts.floor("s").isoformat()   # fixed format keeps string comparison chronological


def _clean(markets: dict) -> dict:
    return {k: v for k, v in markets.items() if k != "top_scores"}


def database_url() -> str | None:
    """DATABASE_URL from the environment, else from a local .env file."""
    url = os.environ.get("DATABASE_URL")
    if not url and ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\s*DATABASE_URL\s*=\s*(.+?)\s*$", line)
            if m:
                url = m.group(1).strip("'\"")
    return url or None


def configured() -> bool:
    """True if there is a log to read: a Postgres URL or an existing SQLite file."""
    return database_url() is not None or DB_FILE.exists()


def describe() -> str:
    url = database_url()
    if url:
        # no user, host or password: workflow logs are public in a public repo
        return "postgres (DATABASE_URL)"
    return f"sqlite: {DB_FILE}"


# --------------------------------------------------------------------- store
class Store:
    def __init__(self, path: Path | None = None, url: str | None = None,
                 schema: str | None = None):
        url = url if url is not None else (None if path is not None else database_url())
        if url:
            import psycopg   # only needed for Postgres
            self.kind = "postgres"
            self.schema = schema or os.environ.get("DATABASE_SCHEMA", "mbtgrandaudit")
            # prepare_threshold=None: safe behind Supabase's connection pooler
            self.con = psycopg.connect(url, prepare_threshold=None, connect_timeout=20)
            self.con.execute(f'CREATE SCHEMA IF NOT EXISTS "{self.schema}"')
            self.con.execute(f'SET search_path TO "{self.schema}"')
            self.where = describe()
        else:
            path = path or DB_FILE
            path.parent.mkdir(parents=True, exist_ok=True)
            self.kind = "sqlite"
            self.con = sqlite3.connect(path)
            self.con.execute("PRAGMA foreign_keys = ON")
            self.where = f"sqlite: {path}"
            self._migrate_sqlite()
        for stmt in SCHEMA.format(**TYPES[self.kind]).split(";"):
            if stmt.strip():
                self.con.execute(stmt)
        self.con.commit()

    def _migrate_sqlite(self):
        cols = [r[1] for r in self.con.execute("PRAGMA table_info(odds)")]
        if "over" in cols:    # 'over' is reserved in Postgres; renamed in v2 of the schema
            self.con.execute("ALTER TABLE odds RENAME COLUMN over TO over_odds")
            self.con.execute("ALTER TABLE odds RENAME COLUMN under TO under_odds")

    # ------------------------------------------------------------ low level
    def _sql(self, q: str) -> str:
        return q.replace("?", "%s") if self.kind == "postgres" else q

    def execute(self, q: str, params=()):
        cur = self.con.cursor()
        cur.execute(self._sql(q), tuple(params))
        return cur

    def executemany(self, q: str, rows):
        rows = list(rows)
        if rows:
            self.con.cursor().executemany(self._sql(q), rows)

    def query(self, q: str, params=()) -> pd.DataFrame:
        cur = self.execute(q, params)
        cols = [d[0] for d in cur.description]
        return pd.DataFrame(cur.fetchall(), columns=cols)

    def scalar(self, q: str, params=()):
        return self.execute(q, params).fetchone()[0]

    def commit(self):
        self.con.commit()

    def close(self):
        self.con.commit()
        self.con.close()

    # ---------------------------------------------------------------- writes
    def add_prediction(self, *, event_id, league, home, away, model_home, model_away, kickoff,
                       predicted_at, version, source, matrix, markets, weights, features,
                       model_matrices) -> int:
        row = (str(event_id), league, home, away, model_home, model_away, _iso(kickoff), _iso(predicted_at),
               version, source, pack(matrix), json.dumps(_clean(markets)), json.dumps(weights),
               json.dumps(features))
        pid = self.execute(_upsert("predictions", PRED_COLS,
                                   ["event_id", "predicted_at", "model_version", "source"], "id"),
                           row).fetchone()[0]
        self.execute("DELETE FROM model_outputs WHERE prediction_id = ?", (pid,))
        self.executemany("INSERT INTO model_outputs (prediction_id, model, weight, matrix) VALUES (?,?,?,?)",
                         [(pid, name, float(weights.get(name, 0.0)), pack(m))
                          for name, m in model_matrices.items() if m is not None])
        return pid

    def add_live(self, pred, league: str, version: str, predicted_at: datetime, source: str = "live") -> int:
        """Log a live prediction. Comparison variants use their own source (e.g.
        'live-pinnacle') and store no odds snapshot, so the main track record is unchanged."""
        fx = pred.fixture
        pid = self.add_prediction(
            event_id=fx.event_id, league=league, home=fx.home, away=fx.away,
            model_home=pred.home, model_away=pred.away, kickoff=fx.kickoff, predicted_at=predicted_at,
            version=version, source=source, matrix=pred.matrix, markets=pred.ensemble,
            weights=pred.weights, features=pred.features, model_matrices=pred.model_matrices)
        if fx.odds and source == "live":
            self.add_odds(fx.event_id, predicted_at, "prediction", fx.odds)
        return pid

    def add_odds(self, event_id, captured_at, kind: str, odds: dict):
        f = lambda k: None if odds.get(k) is None else float(odds[k])
        self.execute(_upsert("odds", ODDS_COLS, ["event_id", "captured_at", "kind"]),
                     (str(event_id), _iso(captured_at), kind, odds.get("source"), f("H"), f("D"), f("A"),
                      f("line"), f("over"), f("under")))

    def add_result(self, event_id, league, hg: int, ag: int, source: str):
        self.execute(_upsert("results", RESULT_COLS, ["event_id"]),
                     (str(event_id), league, int(hg), int(ag), _iso(datetime.now(timezone.utc)), source))

    def add_market_odds(self, event_id, market: str, odds: float, captured_at, kind: str = "manual",
                        bookmaker: str = ""):
        self.execute(_upsert("market_odds", MARKET_ODDS_COLS,
                             ["event_id", "market", "captured_at", "kind", "bookmaker"]),
                     (str(event_id), market, _iso(captured_at), kind, bookmaker or "", float(odds)))

    def add_market_odds_many(self, rows):
        """Rows of (event_id, market, odds, captured_at, kind, bookmaker) in one round trip."""
        self.executemany(_upsert("market_odds", MARKET_ODDS_COLS,
                                 ["event_id", "market", "captured_at", "kind", "bookmaker"]),
                         [(str(ev), market, _iso(at), kind, book or "", float(odds))
                          for ev, market, odds, at, kind, book in rows])

    # ----------------------------------------------------------------- reads
    def find_events(self, home: str, away: str, after: datetime | None = None) -> pd.DataFrame:
        """Logged live fixtures whose team names contain the given text (case-insensitive)."""
        q = ("SELECT event_id, league, home, away, kickoff, MAX(predicted_at) AS predicted_at"
             " FROM predictions WHERE source = 'live' AND LOWER(home) LIKE ? AND LOWER(away) LIKE ?")
        params = [f"%{home.lower()}%", f"%{away.lower()}%"]
        if after is not None:
            q += " AND kickoff >= ?"
            params.append(_iso(after))
        q += " GROUP BY event_id, league, home, away, kickoff ORDER BY kickoff"
        return self.query(q, params)

    def latest_prediction(self, event_id: str) -> pd.Series | None:
        df = self.query("SELECT * FROM predictions WHERE event_id = ? AND source = 'live'"
                        " ORDER BY predicted_at DESC LIMIT 1", (str(event_id),))
        return None if df.empty else df.iloc[0]

    def market_odds_for(self, event_ids) -> pd.DataFrame:
        ids = list(map(str, event_ids))
        if not ids:
            return pd.DataFrame(columns=MARKET_ODDS_COLS)
        out = [self.query(f"SELECT * FROM market_odds WHERE event_id IN ({','.join('?' * len(c))})", c)
               for c in (ids[i:i + 900] for i in range(0, len(ids), 900))]
        return pd.concat(out, ignore_index=True)

    def unsettled(self, before: datetime) -> pd.DataFrame:
        return self.query(
            "SELECT DISTINCT p.event_id, p.league, p.kickoff FROM predictions p"
            " LEFT JOIN results r ON r.event_id = p.event_id"
            " WHERE r.event_id IS NULL AND p.source = 'live' AND p.kickoff < ?", (_iso(before),))

    def upcoming(self, start: datetime, end: datetime) -> pd.DataFrame:
        return self.query(
            "SELECT DISTINCT event_id, league, kickoff FROM predictions"
            " WHERE source = 'live' AND kickoff BETWEEN ? AND ?", (_iso(start), _iso(end)))

    def settled(self, source: str | None = None, league: str | None = None,
                version: str | None = None, since: str | None = None) -> pd.DataFrame:
        """Latest pre-kickoff prediction per event (and version), joined with its result."""
        where, params = ["p.predicted_at <= p.kickoff"], []
        for col, val in (("p.source", source), ("p.league", league), ("p.model_version", version)):
            if val:
                where.append(f"{col} = ?")
                params.append(val)
        if since:
            where.append("p.kickoff >= ?")
            params.append(_iso(since))
        same_version = "AND p2.model_version = p.model_version" if version else ""
        # latest pre-kick-off prediction per event; ties (e.g. a re-run backfill under a
        # new model version) go to the most recently written row
        q = f"""
        SELECT p.*, r.home_goals, r.away_goals FROM predictions p
        JOIN results r ON r.event_id = p.event_id
        WHERE {' AND '.join(where)} AND p.id = (
            SELECT p2.id FROM predictions p2
            WHERE p2.event_id = p.event_id {same_version}
              AND p2.source = p.source AND p2.predicted_at <= p2.kickoff
            ORDER BY p2.predicted_at DESC, p2.id DESC LIMIT 1)
        ORDER BY p.kickoff"""
        return self.query(q, params)

    def model_matrices(self, prediction_ids) -> pd.DataFrame:
        ids = list(map(int, prediction_ids))
        if not ids:
            return pd.DataFrame(columns=["prediction_id", "model", "weight", "matrix"])
        out = []
        for i in range(0, len(ids), 900):     # SQLite parameter limit
            chunk = ids[i:i + 900]
            out.append(self.query(
                f"SELECT * FROM model_outputs WHERE prediction_id IN ({','.join('?' * len(chunk))})", chunk))
        return pd.concat(out, ignore_index=True)

    def odds_for(self, event_ids) -> pd.DataFrame:
        """Odds at prediction time and closing snapshots taken before kick-off."""
        df = self.query(
            "SELECT o.* FROM odds o JOIN (SELECT event_id, MAX(kickoff) AS kickoff FROM predictions"
            " GROUP BY event_id) p ON p.event_id = o.event_id"
            " WHERE o.captured_at <= p.kickoff OR o.kind = 'prediction'")
        return df[df["event_id"].isin(set(map(str, event_ids)))]

    def counts(self) -> dict:
        s = self.scalar
        return {
            "predictions": s("SELECT COUNT(*) FROM predictions"),
            "live": s("SELECT COUNT(*) FROM predictions WHERE source='live'"),
            "backtest": s("SELECT COUNT(*) FROM predictions WHERE source='backtest'"),
            "results": s("SELECT COUNT(*) FROM results"),
            "closing_odds": s("SELECT COUNT(DISTINCT event_id) FROM odds WHERE kind='closing'"),
        }

    # ------------------------------------------------------------ migration
    def copy_from(self, src: "Store", log=print, batch: int = 500) -> dict:
        """Copy every row of another store into this one (ids preserved, existing rows kept)."""
        n = {}
        for table, cols, key in (
                ("predictions", ["id"] + PRED_COLS, ["id"]),
                ("model_outputs", ["prediction_id", "model", "weight", "matrix"], ["prediction_id", "model"]),
                ("odds", ODDS_COLS, ["event_id", "captured_at", "kind"]),
                ("results", RESULT_COLS, ["event_id"]),
                ("market_odds", MARKET_ODDS_COLS, ["event_id", "market", "captured_at", "kind", "bookmaker"])):
            total = src.scalar(f"SELECT COUNT(*) FROM {table}")
            sql = (f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})"
                   f" ON CONFLICT ({', '.join(key)}) DO NOTHING")
            cur = src.execute(f"SELECT {', '.join(cols)} FROM {table} ORDER BY {', '.join(key)}")
            done = 0
            while rows := cur.fetchmany(batch):
                self.executemany(sql, rows)
                self.commit()
                done += len(rows)
                log(f"  {table}: {done}/{total}")
            n[table] = done
        if self.kind == "postgres":    # keep the identity sequence ahead of copied ids
            self.execute("SELECT setval(pg_get_serial_sequence('predictions', 'id'),"
                         " COALESCE((SELECT MAX(id) FROM predictions), 1))")
            self.commit()
        return n
